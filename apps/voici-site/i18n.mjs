#!/usr/bin/env node
// The voi.ci site's strings (surface `voici-site`, the same key/value shape as the other surfaces in i18n/):
//
//   node apps/voici-site/i18n.mjs extract   read every t("…") in apps/voici-site/src into i18n/voici-site/en.json
//   node apps/voici-site/i18n.mjs build     compile i18n/voici-site/<code>.json into apps/voici-site/src/strings.js
//   node apps/voici-site/i18n.mjs check     exit 1 on drift: a string missing from en.json or from a ga language,
//                                           placeholders that differ, a t() whose first argument isn't a literal,
//                                           text a person reads that is not in t() (hardCodedText), or a stale strings.js
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..", "..");
const SRC = join(here, "src");
const SURFACE = join(ROOT, "i18n", "voici-site");
const LOCALES = JSON.parse(readFileSync(join(ROOT, "i18n", "locales.json"), "utf8"));

const CALL = /\bt\(\s*"((?:[^"\\]|\\.)*)"/g;
const BAD_CALL = /(?<![\w.])t\(\s*(?!"|source)/g;

export function extractStrings() {
  const out = new Map();
  const bad = [];
  for (const f of readdirSync(SRC).filter((x) => x.endsWith(".js") && x !== "strings.js" && x !== "i18n.js").sort()) {
    const text = readFileSync(join(SRC, f), "utf8");
    const lines = text.split("\n");
    lines.forEach((line, i) => {
      for (const m of line.matchAll(CALL)) {
        const s = JSON.parse(`"${m[1]}"`);
        if (!out.has(s)) out.set(s, `voici-site/${f}:${i + 1}`);
      }
      if (f !== "i18n.js") for (const m of line.matchAll(BAD_CALL)) bad.push(`${f}:${i + 1}: t() needs a string literal first (${line.trim().slice(0, 80)})`);
    });
  }
  return { strings: out, bad };
}

// Text a person reads must go through t(): a literal that reads as a sentence or a label (a capital, then words, or
// sentence punctuation) and is not t()'s first argument fails `check`. KEEP lists the ones that stay as written.
const PROSE = /^[A-Z][a-z']+(?:[ ,][^\s]+)+$|^[A-Z][a-z]{2,}[.!?…]$/;
const LITERAL = /(?<![\w.$])(t\(\s*)?(["'`])((?:(?!\2)[^\\\n]|\\.)*)\2/g;
const KEEP = new Map([
  // the worker's fallback when IndexedDB holds no notice; flagship-web's enableReplyAlerts stores the localized
  // {title, body} (t("You have a reply on voi.ci.")) before it subscribes, so a visitor never sees this one
  ["sw.js", new Set(["You have a reply on voi.ci."])],
]);
/** The hard-coded text in one source file's lines (`f` names the file in the messages and in KEEP). */
export function hardCodedIn(f, source) {
  const out = [];
  source.split("\n").forEach((line, i) => {
    if (/^\s*(\/\/|\*|\/\*)/.test(line)) return;
    for (const m of line.matchAll(LITERAL)) {
      if (m[1]) continue;
      const text = m[3].replace(/\$\{[^}]*\}/g, "0");
      if (PROSE.test(text) && !/^[\w.-]+\/|https?:|^[A-Z][\w-]*$/.test(text) && !KEEP.get(f)?.has(m[3])) out.push(`${f}:${i + 1}: hard-coded text, wrap it in t(): ${JSON.stringify(m[3]).slice(0, 90)}`);
    }
  });
  return out;
}
export function hardCodedText() {
  return readdirSync(SRC)
    .filter((x) => x.endsWith(".js") && !["strings.js", "i18n.js", "config.js"].includes(x))
    .sort()
    .flatMap((f) => hardCodedIn(f, readFileSync(join(SRC, f), "utf8")));
}

const tokens = (s) => [...s.matchAll(/\{\d+\}/g)].map((m) => m[0]).sort().join(",");
const read = (code) => {
  const f = join(SURFACE, `${code}.json`);
  return existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : {};
};

export function stringsModule() {
  const en = read("en");
  const keys = Object.keys(en);
  const locales = LOCALES.locales.filter((l) => l.status === "ga").map((l) => ({ code: l.code, native: l.native, dir: l.dir }));
  const table = {};
  for (const l of locales) {
    if (l.code === LOCALES.source) continue;
    const tr = read(l.code);
    table[l.code] = Object.fromEntries(keys.filter((k) => typeof tr[k] === "string").map((k) => [k, tr[k]]));
  }
  return (
    "// GENERATED by `node apps/voici-site/i18n.mjs build` from i18n/voici-site/*.json and i18n/locales.json. Do not edit.\n" +
    `export const LOCALES = ${JSON.stringify(locales)};\n` +
    `export const STRINGS = ${JSON.stringify(table, null, 1)};\n`
  );
}

export function checkI18n() {
  const problems = [];
  const { strings, bad } = extractStrings();
  problems.push(...bad, ...hardCodedText());
  const en = read("en");
  for (const s of strings.keys()) if (!(s in en)) problems.push(`not in i18n/voici-site/en.json: ${JSON.stringify(s)}`);
  for (const s of Object.keys(en)) if (!strings.has(s)) problems.push(`unused in en.json: ${JSON.stringify(s)}`);
  for (const l of LOCALES.locales) {
    if (l.code === LOCALES.source) continue;
    const tr = read(l.code);
    for (const s of Object.keys(en)) {
      if (typeof tr[s] !== "string") {
        if (l.status === "ga") problems.push(`${l.code}: missing ${JSON.stringify(s)}`);
      } else if (tokens(tr[s]) !== tokens(s)) problems.push(`${l.code}: placeholders differ in ${JSON.stringify(s)}`);
    }
  }
  if (readFileSync(join(SRC, "strings.js"), "utf8") !== stringsModule()) problems.push("apps/voici-site/src/strings.js is stale: run node apps/voici-site/i18n.mjs build");
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const cmd = process.argv[2];
  if (cmd === "extract") {
    const { strings, bad } = extractStrings();
    if (bad.length) {
      console.error(bad.join("\n"));
      process.exit(1);
    }
    const old = read("en");
    const next = {};
    for (const [s, ctx] of strings) next[s] = { en: s, ctx, ...(old[s]?.note ? { note: old[s].note } : {}) };
    writeFileSync(join(SURFACE, "en.json"), JSON.stringify(next, null, 2) + "\n");
    console.log(`voici-site: ${strings.size} strings`);
  } else if (cmd === "build") {
    writeFileSync(join(SRC, "strings.js"), stringsModule());
    console.log("voici-site: wrote src/strings.js");
  } else if (cmd === "check") {
    const p = checkI18n();
    if (p.length) {
      console.error(p.join("\n"));
      process.exit(1);
    }
    console.log("voici-site: strings ok");
  } else {
    console.error("usage: node apps/voici-site/i18n.mjs extract|build|check");
    process.exit(2);
  }
}
