#!/usr/bin/env node
/**
 * Golden vectors for finding an account's registered IRK from its UMK seed
 * (key-file import, the recovery path).
 *
 * The three clients derive the IRK from the UMK three different ways, and every
 * account in production holds whichever one its creating client used:
 *   web      HKDF-SHA256(umk, salt = "",                  info = "flagship.irk.v<n>")  webapp, @flagship/protocol
 *   ios      HKDF-SHA256(umk, salt = "",                  info = "flagship/irk/v<n>")  iOS Keystore
 *   android  HKDF-SHA256(umk, salt = "flagship/irk/v<n>", info = "ed25519-seed")       Android Keystore
 * so an importer can't assume its own v1. It derives every scheme at v1..maxVersion,
 * takes the one whose public key equals the IRK `.com` serves for the account
 * (GET /api/username/<u> irkPub) as the OLD key, and rotates to its OWN scheme at
 * the matched version + 1 (versions only climb, so a displaced key never returns).
 * No match: the file is not this account's current key, and nothing is sent.
 *
 * Read by apps/web/tests/irkLineage.test.ts, Android IrkLineageTest and iOS
 * IrkLineageVectorTests.
 *
 * Run:          node tools/irk-lineage-vectors.mjs
 * CI freshness: node tools/irk-lineage-vectors.mjs --check
 */
import { createPrivateKey, createPublicKey, hkdfSync } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const out = resolve(root, "packages/protocol/test-vectors/irk-lineage/vectors.json");

const MAX_VERSION = 16;
const SCHEMES = {
  web: { salt: "", info: "flagship.irk.v{n}" },
  ios: { salt: "", info: "flagship/irk/v{n}" },
  android: { salt: "flagship/irk/v{n}", info: "ed25519-seed" },
};
const PKCS8_ED25519 = Buffer.from("302e020100300506032b657004220420", "hex");

const hex = (b) => Buffer.from(b).toString("hex");
const fill = (s, n) => s.replaceAll("{n}", String(n));
function irkSeed(umk, scheme, n) {
  const s = SCHEMES[scheme];
  return Buffer.from(hkdfSync("sha256", umk, Buffer.from(fill(s.salt, n)), Buffer.from(fill(s.info, n)), 32));
}
function pubOf(seed) {
  const k = createPrivateKey({ key: Buffer.concat([PKCS8_ED25519, seed]), format: "der", type: "pkcs8" });
  return createPublicKey(k).export({ format: "der", type: "spki" }).subarray(12);
}
const pubHex = (umk, scheme, n) => hex(pubOf(irkSeed(umk, scheme, n)));

const umk = Buffer.from(Array.from({ length: 32 }, (_, i) => (i * 7 + 3) & 0xff));
const otherUmk = Buffer.from(Array.from({ length: 32 }, (_, i) => 0xf0 - i));

const keys = [];
for (const scheme of Object.keys(SCHEMES)) {
  for (let n = 1; n <= 3; n++) {
    keys.push({ scheme, version: n, seedHex: hex(irkSeed(umk, scheme, n)), pubHex: pubHex(umk, scheme, n) });
  }
}

function importCase(name, scheme, version) {
  const importer = {};
  for (const own of Object.keys(SCHEMES)) {
    importer[own] = { newVersion: version + 1, newPubHex: pubHex(umk, own, version + 1) };
  }
  return { name, registered: { scheme, version }, registeredPubHex: pubHex(umk, scheme, version), importer };
}

const vectors = {
  description:
    "Key-file import: find the account's registered IRK among every client's derivation of the UMK (v1..maxVersion), sign the re-pair's oldIrkSignature with it, and rotate to the importer's own scheme at matched version + 1. Generated by tools/irk-lineage-vectors.mjs.",
  maxVersion: MAX_VERSION,
  schemes: SCHEMES,
  umkSeedHex: hex(umk),
  keys,
  imports: [
    importCase("account created on the webapp", "web", 1),
    importCase("account created on iOS", "ios", 1),
    importCase("account created on Android", "android", 1),
    importCase("webapp account after one key-file import", "web", 2),
    importCase("Android account after one key-file import", "android", 2),
    importCase("iOS account rotated twice", "ios", 3),
  ],
  noMatch: [
    { name: "another account's key", registeredPubHex: pubHex(otherUmk, "android", 1) },
    { name: "rotated past maxVersion", registeredPubHex: pubHex(umk, "web", MAX_VERSION + 1) },
  ],
};

const text = JSON.stringify(vectors, null, 2) + "\n";
if (process.argv.includes("--check")) {
  const cur = await readFile(out, "utf8").catch(() => "");
  if (cur !== text) {
    console.error("irk-lineage vectors are stale: run node tools/irk-lineage-vectors.mjs");
    process.exit(1);
  }
  console.log("irk-lineage vectors up to date");
} else {
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, text);
  console.log(`wrote ${out}`);
}
