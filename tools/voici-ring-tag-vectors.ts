/**
 * Shared vectors for names on a locked phone (docs/voici-locked-caller-names.md): the ring-back's ring tag key and
 * tag, the locked-name key, and the attach body's optional `ringTagKey` (packages/protocol/src/voiciCallModes.ts).
 * Read by TS (packages/protocol/tests/voiciRingTagVectors.test.ts), Swift (FlagshipSharedTests/VoiciRingTagVectorTests)
 * and Kotlin (core/voici/VoiciRingTagVectorsTest).
 *
 *   npx tsx tools/voici-ring-tag-vectors.ts          write
 *   npx tsx tools/voici-ring-tag-vectors.ts --check  exit 1 when stale
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import * as P from "../packages/protocol/src/index.js";

const ROOT = resolve(import.meta.dirname, "..");
const OUT = resolve(ROOT, "packages/protocol/test-vectors/voici/ring-tag.json");
const H = (b: Uint8Array) => Buffer.from(b).toString("hex");

const messagesSecret = new Uint8Array(32).map((_, i) => (i * 7 + 3) & 0xff);
const pageId = "3f".repeat(16);
const otherPageId = "a1".repeat(16);
const tagKey = P.deriveVoiciRingTagKey(messagesSecret, pageId);
const otherTagKey = P.deriveVoiciRingTagKey(messagesSecret, otherPageId);
const ringIds = ["00".repeat(16), "5c".repeat(16), "0123456789abcdef0123456789abcdef"];
const tags = ringIds.map((ringId) => ({ ringId, tag: P.voiciRingTag(tagKey, ringId), otherPageTag: P.voiciRingTag(otherTagKey, ringId) }));
if (new Set(tags.map((t) => t.tag)).size !== tags.length) throw new Error("tags repeat");

const pseudonymPubs = ["11".repeat(32), "e0".repeat(32)];
const lockedNames = pseudonymPubs.map((pseudonymPub) => ({ pseudonymPub, key: P.voiciLockedNameKey(pseudonymPub) }));

const order = { order: { pageId, conv: "22".repeat(16), op: "attach", issuedAt: 1_700_000_000_000 }, signer: "pseudonym", from: "33".repeat(32), sig: "44".repeat(64) };
const key = H(tagKey);
const bodyCases: [string, unknown, string | null][] = [
  ["no key", order, "none"],
  ["a key", { ...order, ringTagKey: key }, key],
  ["uppercase key", { ...order, ringTagKey: key.toUpperCase() }, null],
  ["short key", { ...order, ringTagKey: key.slice(2) }, null],
  ["null key", { ...order, ringTagKey: null }, null],
  ["a key on a browser order", { ...order, signer: "browser", cred: {}, ringTagKey: key }, null],
];
const bodies = bodyCases.map(([name, input, expect]) => {
  const got = P.parseVoiciRingBackBody(input);
  const g = got === null ? null : (got.ringTagKey ?? "none");
  if (g !== expect) throw new Error(`body ${name}: ${g}`);
  return { name, input, expect };
});

const doc = {
  note: "names on a locked phone (docs/voici-locked-caller-names.md); generated by tools/voici-ring-tag-vectors.ts",
  tagRingTag: P.TAG_VOICI_RING_TAG,
  tagLockedName: P.TAG_VOICI_LOCKED_NAME,
  messagesSecret: H(messagesSecret),
  pageId,
  otherPageId,
  tagKey: H(tagKey),
  otherTagKey: H(otherTagKey),
  tags,
  lockedNames,
  bodies,
};

const text = JSON.stringify(doc, null, 2) + "\n";
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(OUT, "utf8");
  } catch {
    /* missing */
  }
  if (cur !== text) {
    console.error(`${OUT} is stale; run npx tsx tools/voici-ring-tag-vectors.ts`);
    process.exit(1);
  }
  console.log("voici ring-tag vectors up to date");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${text.length} bytes)`);
}
