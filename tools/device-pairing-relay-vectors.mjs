#!/usr/bin/env node
/**
 * Golden vectors for the phone-to-phone pairing relay crypto
 * (apps/web/public/webapp/lib/pairingRelay.js deriveMaterial + AES-GCM).
 *
 * Fixed X25519 keys for both ends derive one shared secret; HKDF yields the
 * AEAD key and the 6-digit code, and fixed-nonce AES-GCM freezes the sealed
 * bytes. The web is run for real (deriveMaterial/aeadOpen) and checked against
 * an independent node:crypto derivation before anything is written, so the file
 * can only hold values the web agrees with. Kotlin loads it
 * (LiveDevicePairingRelayTest) and must derive the same code and open the same
 * ciphertext.
 *
 * Run:          node tools/device-pairing-relay-vectors.mjs
 * CI freshness: node tools/device-pairing-relay-vectors.mjs --check
 */
import { createCipheriv, createPrivateKey, createPublicKey, diffieHellman, hkdfSync } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(import.meta.dirname, "..");
const relay = await import(pathToFileURL(resolve(root, "apps/web/public/webapp/lib/pairingRelay.js")).href);

const hex = (b) => Buffer.from(b).toString("hex");
const b64u = (b) => Buffer.from(b).toString("base64url");
const PKCS8_X25519 = Buffer.from("302e020100300506032b656e04220420", "hex");
const SPKI_X25519_LEN = 12;

const adminPriv = Buffer.from(Array.from({ length: 32 }, (_, i) => i + 1));
const incomingPriv = Buffer.from(Array.from({ length: 32 }, (_, i) => 0xa0 + i));

const privKey = (raw) => createPrivateKey({ key: Buffer.concat([PKCS8_X25519, raw]), format: "der", type: "pkcs8" });
const rawPub = (k) => createPublicKey(k).export({ format: "der", type: "spki" }).subarray(SPKI_X25519_LEN);
const adminPub = rawPub(privKey(adminPriv));
const incomingPub = rawPub(privKey(incomingPriv));

const shared = diffieHellman({ privateKey: privKey(adminPriv), publicKey: createPublicKey(privKey(incomingPriv)) });
const salt = Buffer.from("flagship/qr/v1");
const kEnc = Buffer.from(hkdfSync("sha256", shared, salt, Buffer.from("flagship/qr/enc/v1"), 32));
const sasBytes = Buffer.from(hkdfSync("sha256", shared, salt, Buffer.from("flagship/qr/sas/v1"), 4));
const sas = String(sasBytes.readUInt32BE(0) % 1_000_000).padStart(6, "0");

const webKey = (raw) =>
  crypto.subtle.importKey("pkcs8", Buffer.concat([PKCS8_X25519, raw]), { name: "X25519" }, false, ["deriveBits"]);
const webAdmin = await relay.deriveMaterial(await webKey(adminPriv), b64u(incomingPub));
const webIncoming = await relay.deriveMaterial(await webKey(incomingPriv), b64u(adminPub));
if (webAdmin.sas !== sas || webIncoming.sas !== sas) throw new Error("web SAS disagrees with the independent derivation");

const seal = async (plaintext, nonce) => {
  const c = createCipheriv("aes-256-gcm", kEnc, nonce);
  const ct = Buffer.concat([c.update(plaintext), c.final(), c.getAuthTag()]);
  const opened = Buffer.from(await relay.aeadOpen(webIncoming.kEncDecrypt, b64u(ct), b64u(nonce))).toString();
  if (opened !== plaintext) throw new Error("web could not open the fixed ciphertext");
  return { plaintext, nonceB64u: b64u(nonce), ciphertextB64u: b64u(ct) };
};

const leg1Plaintext = JSON.stringify({
  devicePubHex: "ab".repeat(32),
  deviceId: "00112233445566778899aabbccddeeff",
  returnSid: "cmV0dXJuLXNpZC0wMDAwMQ",
  returnPkB64u: b64u(Buffer.alloc(32, 7)),
});
const bundlePlaintext = JSON.stringify({ umkSeedHex: "cd".repeat(32), admitSig: "ef".repeat(64) });

const out = {
  note: "Golden vectors for the pairing relay crypto, generated by tools/device-pairing-relay-vectors.mjs against the web's deriveMaterial. Kotlin derives the same SAS and opens the same ciphertexts.",
  adminPrivHex: hex(adminPriv),
  adminPubB64u: b64u(adminPub),
  incomingPrivHex: hex(incomingPriv),
  incomingPubB64u: b64u(incomingPub),
  kEncHex: hex(kEnc),
  sas,
  leg1Payload: await seal(leg1Plaintext, Buffer.from("000102030405060708090a0b", "hex")),
  bundle: await seal(bundlePlaintext, Buffer.from("0b0a09080706050403020100", "hex")),
};

const file = resolve(root, "test-vectors", "device-pairing-relay.json");
const text = JSON.stringify(out, null, 2) + "\n";
if (process.argv.includes("--check")) {
  const current = await readFile(file, "utf8").catch(() => "");
  if (current !== text) {
    console.error("test-vectors/device-pairing-relay.json is stale; rerun node tools/device-pairing-relay-vectors.mjs");
    process.exit(1);
  }
} else {
  await writeFile(file, text);
  console.log("wrote", file);
}
