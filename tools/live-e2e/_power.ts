import { bytesToHex } from "@noble/hashes/utils";
import { signPhoneOrder, type PhoneOrder } from "@flagship/protocol";
import { Account } from "./lib/fleet.js";
import { postJson } from "./lib/harness.js";
const user = process.argv[2]!;
const fqdn = `home.${user}.gym.flagship.services`;
const A = new Account(user);
const power: PhoneOrder = { type: "power-off", serverId: fqdn, mode: (process.argv[3] as "restart" | "off") ?? "restart", issuedAt: Date.now() };
const p = await postJson(`https://${fqdn}/api/power`, { request: power, signature: bytesToHex(signPhoneOrder(power, A.keys.adminRoot)) });
console.log(p.status, p.text.slice(0, 300));
