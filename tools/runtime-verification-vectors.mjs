#!/usr/bin/env node
// Shared vectors for the server page's "Runtime" section (release plan G2). The webapp's lib/runtimeVerification.js
// GENERATES them (English strings); the webapp, iOS and Android tests check their own presentation against them.
//
//   node tools/runtime-verification-vectors.mjs           write
//   node tools/runtime-verification-vectors.mjs --check   fail when stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "packages/protocol/test-vectors/runtime-verification/vectors.json");
const L = await import(pathToFileURL(resolve(ROOT, "apps/web/public/webapp/lib/runtimeVerification.js")).href);

const base = {
  runtime: "node",
  version: "24.22.1",
  activeVersion: "24.22.1",
  target: "linux-amd64",
  officialUrl: "https://nodejs.org/dist/v24.22.1/node-v24.22.1-linux-x64.tar.gz",
  sourceUrl: "https://nodejs.org/dist/v24.22.1/",
  shasumsUrl: "https://nodejs.org/dist/v24.22.1/SHASUMS256.txt",
  archiveFile: "node-v24.22.1-linux-x64.tar.gz",
  expectedArchiveSha256: "eb6728e77c576a35162c122c45ccadf224d89ff00abc8dae46cc2897c6002d7c",
  expectedExecutableSha256: "e32e2d16081cf644f88392934288086e7662529d0d43277c34f7aad2207cfafb",
  executablePath: "/opt/flagship/.runtime/node/bin/node",
  localExecutableSha256: "e32e2d16081cf644f88392934288086e7662529d0d43277c34f7aad2207cfafb",
  matchesLock: true,
  upstream: { status: "verified-at-release", signer: "5be8a3f6c8a5c01d106c0ad820b1a390b168d356" },
  flagship: { status: "verified", expectedArchiveSha256: "eb6728e77c576a35162c122c45ccadf224d89ff00abc8dae46cc2897c6002d7c", sequence: 1, release: "0.3", version: "24.22.1", validUntil: 1790000000000, matchesLock: true, checkedAt: 1780000000000 },
  lockSha256: "0f".repeat(32),
  pageUrl: "https://flagshipserver.com/runtime",
  manifestUrl: "https://flagshipserver.com/api/runtime/manifest",
};
const views = [
  ["all verified", base],
  ["not published yet", { ...base, flagship: { status: "not-published" } }],
  ["site unreachable", { ...base, flagship: { status: "unavailable", checkedAt: 1 } }],
  ["manifest expired", { ...base, flagship: { ...base.flagship, status: "expired" } }],
  ["manifest rolled back", { ...base, flagship: { ...base.flagship, status: "rollback" } }],
  ["release ahead of the manifest", { ...base, flagship: { ...base.flagship, matchesLock: false } }],
  ["swapped executable", { ...base, localExecutableSha256: "00".repeat(32), matchesLock: false }],
  ["not hashed yet", { ...base, localExecutableSha256: null, matchesLock: false, upstream: { status: "unknown", signer: null } }],
  ["arm64", { ...base, target: "linux-arm64", archiveFile: "node-v24.22.1-linux-arm64.tar.gz", officialUrl: "https://nodejs.org/dist/v24.22.1/node-v24.22.1-linux-arm64.tar.gz" }],
];
const cases = views.map(([name, view]) => ({
  name,
  view,
  expect: {
    present: L.runtimeView({ runtime: view }) !== null,
    platform: L.platformLabel(view.target),
    flagship: L.flagshipStatus(view),
    upstream: L.upstreamStatus(view),
    local: L.localStatus(view),
    notes: L.runtimeNotes(view),
    commands: L.runtimeCommands(view),
  },
}));
cases.push({ name: "an older server reports nothing", view: null, expect: { present: false } });
const text = JSON.stringify({ schema: 1, about: "Generated by tools/runtime-verification-vectors.mjs from apps/web/public/webapp/lib/runtimeVerification.js. English strings; tone is good|neutral|bad.", cases }, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) {
    console.error("runtime-verification vectors are stale: run node tools/runtime-verification-vectors.mjs");
    process.exit(1);
  }
  console.log("runtime-verification vectors are fresh");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${cases.length} cases)`);
}
