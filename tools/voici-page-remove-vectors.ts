#!/usr/bin/env -S npx tsx
/**
 * Writes packages/protocol/test-vectors/voici-page-remove/vectors.json from packages/protocol/src/voiciPageRemove.ts
 * (docs/voici-and-messages.md §3.3): the canonical bytes, the signed envelope, and checkVoiciPageRemove's answer for
 * a valid removal and each refusal. Seeds are test-only (32 bytes of one value), the same keys as test-vectors/voici.
 *
 *   npx tsx tools/voici-page-remove-vectors.ts          write
 *   npx tsx tools/voici-page-remove-vectors.ts --check  fail when the file is stale
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import * as P from "../packages/protocol/src/index.js";

const OUT = resolve(import.meta.dirname, "..", "packages/protocol/test-vectors/voici-page-remove/vectors.json");
const H = (b: Uint8Array) => Buffer.from(b).toString("hex");
const fill = (n: number, v: number) => new Uint8Array(n).fill(v);
const T0 = 1_800_000_000_000;

const adminRootSeed = fill(32, 0x33);
const adminRootPub = H(P.ed.getPublicKey(adminRootSeed));
const irkSeed = fill(32, 0x34);
const irkPub = H(P.ed.getPublicKey(irkSeed));
const otherSeed = fill(32, 0x35);
const pageId = "ab".repeat(16);
const username = "alice";

const fields = { username, pageId, seq: 4, issuedAt: T0 };
const signed = P.signVoiciPageRemove({ ...fields, signerKind: "admin-root" }, adminRootSeed);
const signedIrk = P.signVoiciPageRemove({ ...fields, signerKind: "irk" }, irkSeed);
const ctx = { username, sensitiveKind: "admin-root" as const, sensitivePub: adminRootPub, storedSeq: 3, storedPageId: pageId, now: T0 };
const ctxIrk = { ...ctx, sensitiveKind: "irk" as const, sensitivePub: irkPub };

const tampered = { ...signed, signature: signed.signature.replace(/^./, signed.signature[0] === "0" ? "1" : "0") };
const otherSigned = P.signVoiciPageRemove({ ...fields, signerKind: "admin-root" }, otherSeed);

type Case = { name: string; remove: unknown; ctx: typeof ctx | typeof ctxIrk; expected: string };
const cases: Case[] = [
  { name: "valid (admin root)", remove: signed, ctx, expected: "ok" },
  { name: "valid (IRK, account pins no admin root)", remove: signedIrk, ctx: ctxIrk, expected: "ok" },
  { name: "issuedAt 10 minutes off is still fresh", remove: signed, ctx: { ...ctx, now: T0 + P.VOICI_INDEX_SKEW_MS }, expected: "ok" },
  { name: "extra key", remove: { ...signed, extra: 1 }, ctx, expected: "malformed" },
  { name: "missing key", remove: (({ signerKind: _k, ...r }) => r)(signed), ctx, expected: "malformed" },
  { name: "wrong kind", remove: { ...signed, kind: "VoiciPage" }, ctx, expected: "malformed" },
  { name: "uppercase username", remove: { ...signed, username: "Alice" }, ctx, expected: "malformed" },
  { name: "another account's removal", remove: signed, ctx: { ...ctx, username: "bob" }, expected: "malformed" },
  { name: "seq 0", remove: { ...signed, seq: 0 }, ctx, expected: "malformed" },
  { name: "signed by the IRK while the account pins an admin root", remove: signedIrk, ctx, expected: "wrong-signer" },
  { name: "signed by some other key", remove: otherSigned, ctx, expected: "wrong-signer" },
  { name: "tampered signature", remove: tampered, ctx, expected: "bad-signature" },
  { name: "fields changed after signing", remove: { ...signed, seq: 5 }, ctx: { ...ctx, storedSeq: 4 }, expected: "bad-signature" },
  { name: "another page of the account", remove: signed, ctx: { ...ctx, storedPageId: "cd".repeat(16) }, expected: "wrong-page" },
  { name: "no stored page", remove: signed, ctx: { ...ctx, storedPageId: null as unknown as string }, expected: "wrong-page" },
  { name: "stale", remove: signed, ctx: { ...ctx, now: T0 + P.VOICI_INDEX_SKEW_MS + 1 }, expected: "stale" },
  { name: "from the future", remove: signed, ctx: { ...ctx, now: T0 - P.VOICI_INDEX_SKEW_MS - 1 }, expected: "stale" },
  { name: "replay after it was applied (stored seq is now 4)", remove: signed, ctx: { ...ctx, storedSeq: 4 }, expected: "seq-conflict" },
  { name: "skips a seq", remove: signed, ctx: { ...ctx, storedSeq: 2 }, expected: "seq-conflict" },
];
for (const c of cases) {
  const r = P.checkVoiciPageRemove(c.remove, c.ctx);
  const got = r.ok ? "ok" : r.code;
  if (got !== c.expected) throw new Error(`${c.name}: got ${got}, want ${c.expected}`);
}

const doc = {
  description:
    "voi.ci page removal vectors (docs/voici-and-messages.md §3.3), produced by packages/protocol/src/voiciPageRemove.ts. Generated by tools/voici-page-remove-vectors.ts; do not edit. Seeds are test-only (32 bytes of one value). `expected` is \"ok\" or the refusal code checkVoiciPageRemove returns; checks run in the order malformed, wrong-signer, bad-signature, wrong-page, stale, seq-conflict. A null storedPageId means no stored page.",
  tag: P.TAG_VOICI_PAGE_REMOVE,
  t0: T0,
  skewMs: P.VOICI_INDEX_SKEW_MS,
  keys: { adminRootSeed: H(adminRootSeed), adminRootPub, irkSeed: H(irkSeed), irkPub, otherSeed: H(otherSeed) },
  fields,
  canonical: new TextDecoder().decode(P.canonicalVoiciPageRemove(fields)),
  signed,
  signedIrk,
  cases,
};

const text = JSON.stringify(doc, null, 2) + "\n";
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(OUT, "utf8");
  } catch {
    /* missing */
  }
  if (cur !== text) {
    console.error(`${OUT} is stale; run npx tsx tools/voici-page-remove-vectors.ts`);
    process.exit(1);
  }
  console.log("voici-page-remove vectors up to date");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${text.length} bytes)`);
}
