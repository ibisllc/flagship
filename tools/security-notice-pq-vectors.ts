#!/usr/bin/env -S npx tsx
/**
 * Vectors for the PQ half of security notices (docs/architecture-v2/pq-suites.md §14). The TS
 * port GENERATES them; packages/protocol, the webapp, Swift and Kotlin check every case under an
 * empty pin and under a pin that names the test release key.
 *
 * Run:          npx tsx tools/security-notice-pq-vectors.ts
 * CI freshness: npx tsx tools/security-notice-pq-vectors.ts --check
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { ed25519 } from "@noble/curves/ed25519.js";
import { hybridSigKeygen, hybridSign } from "../packages/protocol/src/pqHybrid.js";
import { canonicalPqKeyBinding, type PqKeyBindingStatement, type PqKeyBindingWire } from "../packages/protocol/src/pqTrust.js";
import { releasePqKeyId } from "../packages/protocol/src/releaseEndorsementPq.js";
import {
  SECURITY_NOTICE_PQ_SUBJECT,
  TAG_SECURITY_NOTICE,
  canonicalSecurityNotice,
  parseSecurityNotice,
  signSecurityNotice,
  verifySecurityNotice,
  type SecurityNotice,
  type SecurityNoticeBody,
} from "../packages/protocol/src/securityNotice.js";

const OUT = resolve(import.meta.dirname, "..", "packages/protocol/test-vectors/security-notice/pq-vectors.json");
const hex = (b: Uint8Array): string => Buffer.from(b).toString("hex");
const fill = (n: number, v: number): Uint8Array => new Uint8Array(n).fill(v);
const zero = (s: string, from: number, to: number): string => s.slice(0, from * 2) + "00".repeat(to - from) + s.slice(to * 2);
const T0 = 1792000000000;

function releaseKey(a: number, b: number) {
  const edSeed = fill(32, a);
  const { publicKey, secretKey } = hybridSigKeygen(edSeed, fill(32, b));
  const st: PqKeyBindingStatement = { role: "release-key", subjectId: SECURITY_NOTICE_PQ_SUBJECT, ed25519PubHex: hex(publicKey.subarray(0, 32)), mldsaPubHex: hex(publicKey.subarray(32)), issuedAt: T0 - 86_400_000 };
  const binding: PqKeyBindingWire = { v: 1, ...st, signature: hex(hybridSign(secretKey, "flagship/pq-key-binding/v1", canonicalPqKeyBinding(st), { deterministic: true })) };
  return { edSeed, secretKey, binding, keyId: releasePqKeyId(st.ed25519PubHex, st.mldsaPubHex) };
}

const K = releaseKey(0x77, 0x79);
const OTHER = releaseKey(0x78, 0x7a);
const authority = { publicKey: ed25519.getPublicKey(K.edSeed), privateKey: K.edSeed };
const authorityPub = hex(authority.publicKey);

const body: SecurityNoticeBody = {
  seq: 7,
  kind: "update-required",
  validFrom: T0,
  validUntil: T0 + 10 * 86_400_000,
  eventAt: T0 + 7 * 86_400_000,
  lockFrom: T0 + 7 * 86_400_000,
  platforms: { ios: { minBuild: 12, minProtocol: 0 }, android: { minBuild: 40, minProtocol: 0 } },
  advisoryId: "FSA-2026-009",
  deprecatesProtocol: 0,
  reason: "A flaw in how a signed message is checked lets an attacker act as you.",
  message: "You must update Flagship by {date}.",
};

const classical = signSecurityNotice(body, authority);
const bytes = canonicalSecurityNotice(classical, classical.signedBy);
const pqSig = (k: typeof K) => hex(hybridSign(k.secretKey, TAG_SECURITY_NOTICE, bytes, { deterministic: true }));
const hybrid: SecurityNotice = { ...classical, pq: { binding: K.binding, signature: pqSig(K) } };

const cases: { name: string; notice: unknown }[] = [
  { name: "classical-only", notice: classical },
  { name: "hybrid", notice: hybrid },
  { name: "pq-ed25519-half-zeroed", notice: { ...hybrid, pq: { ...hybrid.pq!, signature: zero(hybrid.pq!.signature, 0, 64) } } },
  { name: "pq-mldsa-half-zeroed", notice: { ...hybrid, pq: { ...hybrid.pq!, signature: zero(hybrid.pq!.signature, 64, 3373) } } },
  { name: "pq-over-other-bytes", notice: { ...hybrid, message: "You must update Flagship now." } },
  {
    name: "pq-lifted-from-other-notice",
    notice: { ...hybrid, pq: { binding: K.binding, signature: hex(hybridSign(K.secretKey, TAG_SECURITY_NOTICE, canonicalSecurityNotice({ ...classical, seq: 6 }, classical.signedBy), { deterministic: true })) } },
  },
  { name: "pq-by-unpinned-key", notice: { ...hybrid, pq: { binding: OTHER.binding, signature: pqSig(OTHER) } } },
  { name: "pq-binding-substituted-mldsa", notice: { ...hybrid, pq: { binding: { ...K.binding, mldsaPubHex: OTHER.binding.mldsaPubHex }, signature: pqSig(K) } } },
  { name: "pq-classical-length", notice: { ...hybrid, pq: { ...hybrid.pq!, signature: classical.signature } } },
  { name: "pq-extra-field", notice: { ...hybrid, pq: { ...hybrid.pq!, extra: 1 } } },
];

const pinned = [K.keyId];
const out = {
  about:
    "The PQ half of flagship/security-notice/v1 (docs/architecture-v2/pq-suites.md §14). DRAFT, pending Q01 external review. Generated by tools/security-notice-pq-vectors.ts. Each case gives the verdict of verifySecurityNotice (\"ok\" or a refusal) with the release PQ pin empty and with the pin naming `pinnedKeyIds`; `authorityKeys` is the ca-track authority. A refusal before the PQ check (\"malformed\") is the same under both pins.",
  authorityKeys: [authorityPub],
  pinnedKeyIds: pinned,
  releaseBinding: K.binding,
  cases: cases.map((c) => {
    const verdict = (pin: string[]) => {
      const n = parseSecurityNotice(c.notice);
      if (!n) return "malformed";
      const v = verifySecurityNotice(n, [authorityPub], pin);
      return v.ok ? "ok" : v.reason;
    };
    return { name: c.name, notice: c.notice, expect: { emptyPin: verdict([]), pinned: verdict(pinned) } };
  }),
};

const text = JSON.stringify(out, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) {
    console.error(`${OUT} is stale: run npx tsx tools/security-notice-pq-vectors.ts`);
    process.exit(1);
  }
  console.log("security-notice PQ vectors are fresh");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
  for (const c of out.cases) console.log(`${c.name}: ${c.expect.emptyPin} / ${c.expect.pinned}`);
}
