#!/usr/bin/env node
// Builds the webapp's two vendored noble bundles under apps/web/public/webapp/vendor/noble-post-quantum/:
//
//   pq-verify.js  the ML-DSA-65 and Ed25519 verifiers the webapp needs to check a box's hybrid key binding
//                 (lib/pqBinding.js, docs/architecture-v2/pq-suites.md §9), and SHA-256 for the owner's
//                 assurance policy digests (lib/assurancePolicy.js). Verify-only: the keyless-web rule keeps
//                 private keys out of website JavaScript.
//   pq-seal.js    for Messages (lib/voiciProtocol.js, docs/voici-and-messages.md): X-Wing (ml_kem768_x25519)
//                 for the hybrid seal, P-256, Ed25519, HKDF, SHA-256/512 and AES-256-GCM. The webapp is a full
//                 account device for Messages (spec §9.5): it signs and seals only with keys its caller passes
//                 in (derived from the account's own UMK), never with a key a website handed it.
//
// Both are bundled from the exact @noble versions in package-lock.json, so the browser runs the same code the
// protocol package's tests run.
//
//   node scripts/build-webapp-pq-vendor.mjs          rebuild both
//   node scripts/build-webapp-pq-vendor.mjs --check  fail if either committed file is stale
import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "apps/web/public/webapp/vendor/noble-post-quantum");
const version = (p) => JSON.parse(readFileSync(join(ROOT, `node_modules/@noble/${p}/package.json`), "utf8")).version;
const pqVersion = version("post-quantum");
const curvesVersion = version("curves");
const hashesVersion = version("hashes");
const ciphersVersion = version("ciphers");

const BUNDLES = [
  {
    file: "pq-verify.js",
    entry: "pq-verify-entry.js",
    contents:
      'export { ml_dsa65 } from "@noble/post-quantum/ml-dsa.js";\nexport { ed25519 } from "@noble/curves/ed25519.js";\nexport { sha256 } from "@noble/hashes/sha2.js";\n',
    header: `// Generated by scripts/build-webapp-pq-vendor.mjs from @noble/post-quantum ${pqVersion}, @noble/curves ${curvesVersion} and @noble/hashes ${hashesVersion} (MIT, Paul Miller). Do not edit.\n`,
  },
  {
    file: "pq-seal.js",
    entry: "pq-seal-entry.js",
    contents: [
      'export { ml_kem768_x25519 } from "@noble/post-quantum/hybrid.js";',
      'export { p256 } from "@noble/curves/nist.js";',
      'export { ed25519, x25519 } from "@noble/curves/ed25519.js";',
      'export { hkdf } from "@noble/hashes/hkdf.js";',
      'export { sha256, sha512 } from "@noble/hashes/sha2.js";',
      'export { gcm } from "@noble/ciphers/aes.js";',
      "",
    ].join("\n"),
    header: `// Generated by scripts/build-webapp-pq-vendor.mjs from @noble/post-quantum ${pqVersion}, @noble/curves ${curvesVersion}, @noble/hashes ${hashesVersion} and @noble/ciphers ${ciphersVersion} (MIT, Paul Miller). For Messages (docs/voici-and-messages.md). Do not edit.\n`,
  },
];

const check = process.argv.includes("--check");
let stale = false;
for (const b of BUNDLES) {
  const r = await build({
    stdin: { contents: b.contents, resolveDir: ROOT, sourcefile: b.entry },
    bundle: true,
    format: "esm",
    minify: true,
    legalComments: "none",
    target: "es2022",
    write: false,
  });
  const text = b.header + r.outputFiles[0].text;
  const out = join(DIR, b.file);
  if (check) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
      console.error(`${out} is stale: run node scripts/build-webapp-pq-vendor.mjs`);
      stale = true;
    }
  } else {
    mkdirSync(DIR, { recursive: true });
    writeFileSync(out, text);
    console.log(`wrote ${out} (${text.length} bytes)`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("webapp pq vendor bundles are fresh");
}
