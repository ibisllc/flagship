#!/usr/bin/env node
// Builds apps/web/public/webapp/vendor/noble-post-quantum/pq-verify.js: the ML-DSA-65 and
// Ed25519 verifiers the webapp needs to check a box's hybrid key binding
// (lib/pqBinding.js, docs/architecture-v2/pq-suites.md §9). Bundled from the exact
// @noble/post-quantum and @noble/curves versions in package-lock.json, so the browser runs the
// same code the protocol package's tests run. The webapp only VERIFIES with it: the keyless-web
// rule keeps private keys out of website JavaScript.
//
//   node scripts/build-webapp-pq-vendor.mjs          rebuild
//   node scripts/build-webapp-pq-vendor.mjs --check  fail if the committed file is stale
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "apps/web/public/webapp/vendor/noble-post-quantum/pq-verify.js");
const pqVersion = JSON.parse(readFileSync(join(ROOT, "node_modules/@noble/post-quantum/package.json"), "utf8")).version;
const curvesVersion = JSON.parse(readFileSync(join(ROOT, "node_modules/@noble/curves/package.json"), "utf8")).version;

const r = await build({
  stdin: {
    contents: 'export { ml_dsa65 } from "@noble/post-quantum/ml-dsa.js";\nexport { ed25519 } from "@noble/curves/ed25519.js";\n',
    resolveDir: ROOT,
    sourcefile: "pq-verify-entry.js",
  },
  bundle: true,
  format: "esm",
  minify: true,
  legalComments: "none",
  target: "es2022",
  write: false,
});
const header = `// Generated by scripts/build-webapp-pq-vendor.mjs from @noble/post-quantum ${pqVersion} and @noble/curves ${curvesVersion} (MIT, Paul Miller). Do not edit.\n`;
const text = header + r.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== text) {
    console.error(`${OUT} is stale: run node scripts/build-webapp-pq-vendor.mjs`);
    process.exit(1);
  }
  console.log("webapp pq vendor bundle is fresh");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${text.length} bytes)`);
}
