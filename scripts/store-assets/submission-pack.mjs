#!/usr/bin/env node
// The store listing texts as one Markdown appendix, for a browser session that can't read the repository
// (docs/runbooks/0.4-store-submission-browser.md). Every field of store/listings/<lang>.json in its own fenced block,
// with its length in code points (the way the consoles count, as in listings.mjs) and the console's locale names.
//
//   node scripts/store-assets/submission-pack.mjs                 print the appendix
//   node scripts/store-assets/submission-pack.mjs --write <doc>   replace the text between the markers in <doc>
//   node scripts/store-assets/submission-pack.mjs --check <doc>   exit 1 if <doc>'s appendix is out of date

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LIMITS, checkListings } from "./listings.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DIR = path.join(ROOT, "store/listings");
const START = "<!-- submission-pack:start (generated by scripts/store-assets/submission-pack.mjs; do not edit by hand) -->";
const END = "<!-- submission-pack:end -->";

const ORDER = ["en", "de", "es", "fr", "ja", "pt-BR", "zh-Hans"];

// The consoles' own names for each language. es fills two App Store localizations with the same text.
const APPSTORE_LOCALE = {
  en: "English (U.S.) `en-US` (primary language)",
  de: "German `de-DE`",
  es: "Spanish (Spain) `es-ES` **and** Spanish (Mexico) `es-MX` (same texts in both)",
  fr: "French `fr-FR`",
  ja: "Japanese `ja`",
  "pt-BR": "Portuguese (Brazil) `pt-BR`",
  "zh-Hans": "Chinese (Simplified) `zh-Hans`",
};
const PLAY_LOCALE = {
  en: "English (United States) – `en-US` (default language)",
  de: "German – `de-DE`",
  es: "Spanish (Spain) – `es-ES` (also Spanish (Latin America) – `es-419` if the listing already has it)",
  fr: "French (France) – `fr-FR`",
  ja: "Japanese – `ja-JP`",
  "pt-BR": "Portuguese (Brazil) – `pt-BR`",
  "zh-Hans": "Chinese (Simplified) – `zh-CN`",
};

const LABEL = {
  appstore: {
    name: "Name (app name) — ONLY if the owner confirmed the new name; otherwise leave the name as it is",
    subtitle: "Subtitle",
    promotionalText: "Promotional Text",
    description: "Description",
    keywords: "Keywords",
    whatsNew: "What's New in This Version",
  },
  playstore: {
    title: "App name — ONLY if the owner confirmed the new name; otherwise leave the name as it is",
    shortDescription: "Short description",
    fullDescription: "Full description",
    whatsNew: "Release notes (the production release, this language)",
  },
};

const len = (s) => [...s].length;

function fence(text) {
  let f = "```";
  while (text.includes(f)) f += "`";
  return `${f}text\n${text}\n${f}`;
}

export function buildAppendix() {
  const out = [];
  out.push("## Appendix: every listing text, exactly", "");
  out.push(
    "Generated from `store/listings/*.json`. Copy the text between the fence lines only (not the word `text`, not the",
    "fences). Counts are characters as the consoles count them. Bullets are the character •; blank lines are part of",
    "the text. The translations are machine drafts: use them as they are.",
    "",
  );
  for (const [store, title] of [["appstore", "App Store Connect"], ["playstore", "Google Play Console"]]) {
    out.push(`### ${title}`, "");
    for (const lang of ORDER) {
      const doc = JSON.parse(fs.readFileSync(path.join(DIR, `${lang}.json`), "utf8"));
      const locale = store === "appstore" ? APPSTORE_LOCALE[lang] : PLAY_LOCALE[lang];
      out.push(`#### ${title}: ${lang} → ${locale}`, "");
      for (const [field, max] of Object.entries(LIMITS[store])) {
        const v = doc[store][field];
        out.push(`**${LABEL[store][field]}** (\`${store}.${field}\`, ${len(v)} / ${max} characters)`, "", fence(v), "");
      }
    }
  }
  return out.join("\n").trimEnd() + "\n";
}

function splice(docText, appendix) {
  const a = docText.indexOf(START);
  const b = docText.indexOf(END);
  if (a < 0 || b < a) throw new Error(`markers missing: put\n${START}\n${END}\nin the document`);
  return docText.slice(0, a) + START + "\n\n" + appendix + "\n" + docText.slice(b);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { problems } = checkListings();
  if (problems.length) { console.error(problems.join("\n") + "\n\nfix the listings first (listings.mjs check)"); process.exit(1); }
  const [mode, file] = process.argv.slice(2);
  const appendix = buildAppendix();
  if (!mode) process.stdout.write(appendix);
  else if ((mode === "--write" || mode === "--check") && file) {
    const cur = fs.readFileSync(file, "utf8");
    const next = splice(cur, appendix);
    if (mode === "--write") { fs.writeFileSync(file, next); console.log(`${file}: appendix written`); }
    else if (next !== cur) { console.error(`${file}: appendix is out of date (run --write)`); process.exit(1); }
    else console.log(`${file}: appendix up to date`);
  } else { console.error("usage: submission-pack.mjs [--write <doc> | --check <doc>]"); process.exit(2); }
}
