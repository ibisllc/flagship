#!/usr/bin/env node
// i18n-linux — gettext catalogs for Flagship Studio on Linux.
//
//   python3 scripts/i18n_linux.py wrap     (one-time) wrap the user-facing strings in tr("…") and write i18n/studio-linux/en.json
//   node scripts/i18n-linux.mjs build [--drafts]   i18n/studio-linux/*.json -> apps/builder-linux/po/<lang>.po (+ .pot),
//                                                  and, when msgfmt exists, locale/<lang>/LC_MESSAGES/flagship-studio.mo for a checkout
//   node scripts/i18n-linux.mjs check | dump | merge | status | lint
//
// The AppImage and Flatpak builds compile po/*.po themselves. Only "ga" languages get a .po unless --drafts.

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { ROOT, locales, targets, readEn, readTr, runCommon, lintSurface } from "./lib/i18n-kv.mjs";

const SURFACE = "studio-linux";
const LINUX = path.join(ROOT, "apps/builder-linux");
const args = process.argv.slice(2);
const cmd = args[0];

const q = (t) => '"' + t.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\t/g, "\\t") + '"';
const poHeader = (lang) => `# Flagship Studio for Linux — ${lang ?? "template"}\n# GENERATED by scripts/i18n-linux.mjs build from i18n/${SURFACE}. Edit the JSON, not this file.\nmsgid ""\nmsgstr ""\n"Project-Id-Version: flagship-studio\\n"\n"MIME-Version: 1.0\\n"\n"Content-Type: text/plain; charset=UTF-8\\n"\n"Content-Transfer-Encoding: 8bit\\n"\n${lang ? `"Language: ${lang}\\n"\n` : ""}\n`;

function emitPo(lang) {
  const en = readEn(SURFACE);
  const tr = lang ? readTr(SURFACE, lang) : {};
  const out = [poHeader(lang)];
  for (const [k, v] of Object.entries(en)) {
    if (v.translatable === false) continue;
    if (lang && typeof tr[k] !== "string") continue;
    out.push(`#: ${v.ctx ?? ""}\n${/\{\d/.test(k) ? "#, python-brace-format\n" : ""}msgid ${q(k)}\nmsgstr ${q(lang ? tr[k] : "")}\n`);
  }
  return out.join("\n");
}

function build() {
  const drafts = args.includes("--drafts");
  const poDir = path.join(LINUX, "po");
  fs.rmSync(poDir, { recursive: true, force: true });
  fs.rmSync(path.join(LINUX, "locale"), { recursive: true, force: true });
  if (!Object.keys(readEn(SURFACE)).length) return;
  fs.mkdirSync(poDir, { recursive: true });
  fs.writeFileSync(path.join(poDir, "flagship-studio.pot"), emitPo(null));
  for (const l of targets.filter((x) => drafts || x.status === "ga")) {
    if (!Object.keys(readTr(SURFACE, l.code)).length) continue;
    const f = path.join(poDir, `${l.gettextId}.po`);
    fs.writeFileSync(f, emitPo(l.gettextId.replace("_", "-")));
    try {
      const mo = path.join(LINUX, "locale", l.gettextId, "LC_MESSAGES");
      fs.mkdirSync(mo, { recursive: true });
      execFileSync("msgfmt", ["--check-format", "-o", path.join(mo, "flagship-studio.mo"), f], { stdio: "pipe" });
    } catch (e) {
      if (e.code !== "ENOENT") { console.error(`${l.gettextId}.po: ${String(e.stderr ?? e)}`); process.exitCode = 1; }
    }
  }
  console.log(`${SURFACE}: wrote ${path.relative(ROOT, poDir)}`);
}

if (cmd === "build") build();
else if (cmd === "check") {
  const problems = [...lintSurface(SURFACE)];
  const en = readEn(SURFACE);
  for (const l of locales.locales.filter((x) => x.status === "ga" && x.code !== locales.source)) {
    const tr = readTr(SURFACE, l.code);
    const missing = Object.keys(en).filter((k) => en[k].translatable !== false && tr[k] == null);
    if (missing.length) problems.push(`${SURFACE}/${l.code} is ga but lacks ${missing.length} strings (first: ${missing[0]})`);
    const f = path.join(LINUX, "po", `${l.gettextId}.po`);
    if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== emitPo(l.gettextId.replace("_", "-"))) problems.push(`${path.relative(ROOT, f)} is stale: run node scripts/i18n-linux.mjs build`);
  }
  if (problems.length) { console.error(problems.join("\n") + `\n\n${problems.length} problem(s)`); process.exit(1); }
  console.log("i18n-linux: ok");
} else if (!runCommon(SURFACE, args)) {
  console.error("usage: i18n-linux.mjs build [--drafts] | check | dump | merge | status | lint");
  process.exit(2);
}
