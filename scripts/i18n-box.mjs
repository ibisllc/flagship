#!/usr/bin/env node
// i18n-box — the text of the pages the box serves itself (invite, sign-in, backup download, landing, 404, "moving").
//
//   node scripts/i18n-box.mjs extract         read t(lang, "…") / tj(lang, "…") calls in packages/server-daemon/src into i18n/box/en.json
//   node scripts/i18n-box.mjs build [--drafts] write packages/server-daemon/src/i18n/catalog.generated.ts (ga languages only, unless --drafts)
//   node scripts/i18n-box.mjs check            fail on drift, placeholder/glossary problems, a ga language missing strings, or a stale catalog
//   node scripts/i18n-box.mjs dump | merge | midx | status | lint     (shared, see scripts/lib/i18n-kv.mjs)
//
// Keys are the English text, as in the webapp. A box ships a new catalog only with an endorsed release.
import fs from "node:fs";
import path from "node:path";
import { ROOT, locales, readEn, writeEn, readTr, lintSurface, runCommon } from "./lib/i18n-kv.mjs";

const SURFACE = "box";
const SRC = path.join(ROOT, "packages/server-daemon/src");
const OUT = path.join(SRC, "i18n/catalog.generated.ts");
const CALL = /\b(?:t|tj)\(\s*lang\s*,\s*("(?:[^"\\\n]|\\.)*"|`(?:[^`\\$]|\\.)*`)/g;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    if (d.isDirectory()) return d.name === "i18n" ? [] : walk(p);
    return d.name.endsWith(".ts") ? [p] : [];
  });
}

/** Every key the source asks for, with the first place it appears. */
function harvest() {
  const found = new Map();
  for (const file of walk(SRC)) {
    const text = fs.readFileSync(file, "utf8");
    for (const m of text.matchAll(CALL)) {
      const lit = m[1];
      // The literal is our own source, so evaluating its escapes is safe.
      const key = lit[0] === '"' ? JSON.parse(lit) : new Function(`return ${lit}`)();
      if (!found.has(key)) found.set(key, `${path.relative(ROOT, file)}:${text.slice(0, m.index).split("\n").length}`);
    }
  }
  return found;
}

const args = process.argv.slice(2);
const cmd = args[0];
const ga = () => locales.locales.filter((l) => l.status === "ga" && l.code !== locales.source);

function catalogSource(langs) {
  const en = readEn(SURFACE);
  const body = langs.map((l) => {
    const tr = readTr(SURFACE, l.code);
    const entries = Object.keys(en).filter((k) => en[k].translatable !== false && typeof tr[k] === "string" && tr[k]).map((k) => [k, tr[k]]);
    return `  ${JSON.stringify(l.code)}: ${JSON.stringify(Object.fromEntries(entries), null, 2).replace(/\n/g, "\n  ")},`;
  });
  return `// GENERATED by scripts/i18n-box.mjs from i18n/box/ and i18n/locales.json (ga languages only). Do not edit.\nexport const CATALOGS: Record<string, Record<string, string>> = {${body.length ? "\n" + body.join("\n") + "\n" : ""}};\n`;
}

if (cmd === "extract") {
  const found = harvest();
  const en = readEn(SURFACE);
  const next = {};
  for (const [key, where] of found) next[key] = { ...(en[key] ?? {}), en: key, ctx: where };
  const gone = Object.keys(en).filter((k) => !found.has(k));
  writeEn(SURFACE, next);
  console.log(`${found.size} strings (${gone.length} no longer in the source)`);
} else if (cmd === "build") {
  const langs = args.includes("--drafts") ? locales.locales.filter((l) => l.code !== locales.source) : ga();
  fs.writeFileSync(OUT, catalogSource(langs));
  console.log(`box: ${langs.length} language(s) in the catalog`);
} else if (cmd === "check") {
  const found = harvest();
  const en = readEn(SURFACE);
  const problems = lintSurface(SURFACE);
  for (const k of found.keys()) if (!en[k]) problems.push(`not in i18n/box/en.json (run node scripts/i18n-box.mjs extract): ${k.slice(0, 70)}`);
  for (const k of Object.keys(en)) if (!found.has(k)) problems.push(`stale in i18n/box/en.json (run extract): ${k.slice(0, 70)}`);
  for (const l of ga()) {
    const tr = readTr(SURFACE, l.code);
    const missing = Object.keys(en).filter((k) => en[k].translatable !== false && !tr[k]);
    if (missing.length) problems.push(`box/${l.code} is ga but lacks ${missing.length} strings (first: ${missing[0].slice(0, 60)})`);
  }
  if (fs.readFileSync(OUT, "utf8") !== catalogSource(ga())) problems.push("packages/server-daemon/src/i18n/catalog.generated.ts is stale: run node scripts/i18n-box.mjs build");
  if (problems.length) { console.error(problems.join("\n") + `\n\n${problems.length} problem(s)`); process.exit(1); }
  console.log("i18n-box: ok");
} else if (!runCommon(SURFACE, args)) {
  console.error("usage: i18n-box.mjs extract | build [--drafts] | check | dump | merge | midx | status | lint");
  process.exit(2);
}
