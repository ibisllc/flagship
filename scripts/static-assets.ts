// Which requests reach the `.com` Worker and which are answered by the static
// assets layer directly, and the files that follow from it. On the Workers Free
// plan every request that runs the Worker counts against 100,000 a day, while a
// request the assets layer answers on its own is free and unlimited; so
// `run_worker_first` in apps/com/wrangler.toml is `"/*"` minus an explicit list
// of static files (`!` patterns). This module is the single reader of that list:
//
//   * reachesWorker(patterns, path)    Cloudflare's matching rule, for the tests and the guard
//   * siteHeadersFile(patterns)        the `_headers` rules for the files served directly
//                                      (the Worker no longer adds its security headers to them)
//   * buildWebappAssets(outDir)        the assets directory of the static-only `flagship-webapp`
//                                      Worker that serves webapp. and remote. (webapp files at the
//                                      root, plus the shared fonts and qrEncoder.js, plus `_headers`)
//   * checkStaticAssets(root)          the predeploy guard (scripts/predeploy-com.sh)
//
// CLI: npx tsx scripts/static-assets.ts check | write-headers | build-webapp [outDir]
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { securityHeaders } from "../apps/com/src/securityHeaders.js";

const here = dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = join(here, "..");

export const PROD_APEX = "flagshipserver.com";
export const PROD_SERVICES_APEX = "flagship.services";
/** Cloudflare: up to 100 `_headers` rules and 100 `run_worker_first` entries. */
export const MAX_HEADER_RULES = 100;
export const MAX_WORKER_FIRST_ENTRIES = 100;
export const SITE_HEADERS_PATH = "apps/web/public/_headers";
export const SITE_HEADERS_BANNER =
  "# GENERATED by `npx tsx scripts/static-assets.ts write-headers` from run_worker_first in\n" +
  "# apps/com/wrangler.toml. Do not edit by hand: the guard and the tests fail on drift.\n" +
  "# One rule per file or folder the assets layer serves WITHOUT running the Worker, carrying the\n" +
  "# headers the Worker would have added (apps/com/src/securityHeaders.ts).\n";

// ---- wrangler.toml ---------------------------------------------------------

/** The `[assets]` table's `run_worker_first` array, in order. */
export function readWorkerFirst(tomlText: string): string[] {
  const assets = tomlText.match(/^\[assets\]\s*$([\s\S]*?)(?=^\[|(?![\s\S]))/m);
  if (!assets) throw new Error("no [assets] table");
  const m = assets[1]!.match(/^run_worker_first\s*=\s*(\[[\s\S]*?\]|true|false)\s*$/m);
  if (!m) throw new Error("no run_worker_first in [assets]");
  if (m[1] === "true") return ["/*"];
  if (m[1] === "false") return [];
  const body = m[1]!
    .split("\n")
    .map((l) => l.replace(/(^|\s)#.*$/, ""))
    .join("\n");
  return [...body.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((x) => x[1]!);
}

export function readAssetsSetting(tomlText: string, key: string): string | undefined {
  const assets = tomlText.match(/^\[assets\]\s*$([\s\S]*?)(?=^\[|(?![\s\S]))/m);
  return assets?.[1]!.match(new RegExp(`^${key}\\s*=\\s*"([^"]*)"`, "m"))?.[1];
}

// ---- Cloudflare's matching rule -------------------------------------------

/** `*` matches any run of characters (slashes included: "deep matching"); the rest is literal. */
export function globToRegExp(pattern: string): RegExp {
  const body = pattern
    .split("*")
    .map((part) => part.replace(/[.+?^${}()|[\]\\]/g, "\\$&"))
    .join(".*");
  return new RegExp(`^${body}$`);
}

/** Does a request for `path` run the Worker first? Negative patterns win over positive ones. */
export function reachesWorker(patterns: readonly string[], path: string): boolean {
  let positive = false;
  for (const p of patterns) {
    if (p.startsWith("!")) {
      if (globToRegExp(p.slice(1)).test(path)) return false;
    } else if (globToRegExp(p).test(path)) positive = true;
  }
  return positive;
}

export function directPatterns(patterns: readonly string[]): string[] {
  return patterns.filter((p) => p.startsWith("!")).map((p) => p.slice(1));
}

// ---- _headers --------------------------------------------------------------

const title = (n: string) => n.replace(/(^|-)([a-z])/g, (_, a, b) => a + b.toUpperCase());

function rule(path: string, kind: "shell" | "site", apex: string, services: string): string {
  const lines = securityHeaders(kind, { apex, services, https: true }).map(([n, v]) => `  ${title(n)}: ${v}`);
  return `${path}\n${lines.join("\n")}\n`;
}

/** `_headers` for apps/web/public: the site headers on every file served without the Worker. */
export function siteHeadersFile(patterns: readonly string[], apex = PROD_APEX, services = PROD_SERVICES_APEX): string {
  const rules = directPatterns(patterns).map((p) => rule(p, "site", apex, services));
  return SITE_HEADERS_BANNER + "\n" + rules.join("\n");
}

/** `_headers` for the static-only webapp Worker: the shell headers on everything. */
export function webappHeadersFile(apex = PROD_APEX, services = PROD_SERVICES_APEX): string {
  return (
    "# GENERATED by scripts/static-assets.ts build-webapp: the headers route.ts adds to webapp. and\n" +
    "# remote. (apps/com/src/securityHeaders.ts), now that the Worker no longer sees these requests.\n\n" +
    rule("/*", "shell", apex, services)
  );
}

export function countHeaderRules(file: string): number {
  return file.split("\n").filter((l) => l.length > 0 && !l.startsWith("#") && !l.startsWith(" ") && !l.startsWith("\t")).length;
}

// ---- the webapp assets directory ----------------------------------------

export interface WebappBuildOptions {
  publicDir?: string;
  apex?: string;
  services?: string;
}

export async function buildWebappAssets(outDir: string, opts: WebappBuildOptions = {}): Promise<{ files: number }> {
  const publicDir = opts.publicDir ?? join(REPO_ROOT, "apps/web/public");
  const { _internal } = await import("../apps/com/src/route.js");
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  cpSync(join(publicDir, "webapp"), outDir, { recursive: true, filter: (src) => !src.endsWith(".DS_Store") });
  // Files the shell imports from the SITE root (route.ts serveWebapp): one copy, no drift.
  for (const f of _internal.WEBAPP_SHARED_ROOT_ASSETS) {
    cpSync(join(publicDir, f.slice(1)), join(outDir, f.slice(1)));
  }
  for (const prefix of _internal.WEBAPP_SHARED_ROOT_PREFIXES) {
    cpSync(join(publicDir, prefix.slice(1)), join(outDir, prefix.slice(1)), {
      recursive: true,
      filter: (src) => !src.endsWith(".DS_Store"),
    });
  }
  writeFileSync(join(outDir, "_headers"), webappHeadersFile(opts.apex, opts.services));
  return { files: listFiles(outDir).length };
}

export function listFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(dir, p).split("\\").join("/"));
    }
  };
  walk(dir);
  return out.sort();
}

