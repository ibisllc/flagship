export interface Finding {
  level: "error";
  message: string;
}

/** Everything the guard and tests check about the `.com` static-asset wiring. */
export function checkStaticAssets(root = REPO_ROOT, tomlOverride?: string): Finding[] {
  const f: Finding[] = [];
  const err = (message: string) => f.push({ level: "error", message });
  const toml = tomlOverride ?? readFileSync(join(root, "apps/com/wrangler.toml"), "utf8");
  let patterns: string[] = [];
  try {
    patterns = readWorkerFirst(toml);
  } catch (e) {
    err(`apps/com/wrangler.toml: ${(e as Error).message}`);
    return f;
  }
  if (patterns.length > MAX_WORKER_FIRST_ENTRIES) err(`run_worker_first has ${patterns.length} entries; Cloudflare allows ${MAX_WORKER_FIRST_ENTRIES}`);
  if (!patterns.includes("/*")) err('run_worker_first must start from "/*": a dynamic path that is not listed would be answered by the assets layer');
  if (readAssetsSetting(toml, "not_found_handling") !== "single-page-application") err("[assets] not_found_handling must stay single-page-application");

  for (const path of MUST_REACH_WORKER) {
    if (!reachesWorker(patterns, path)) err(`${path} is served as a static file but the Worker must see it (a negative pattern shadows it)`);
  }

  const publicDir = join(root, "apps/web/public");
  const files = listFiles(publicDir).filter((p) => p !== "_headers");
  for (const neg of directPatterns(patterns)) {
    const re = globToRegExp(neg);
    // a pattern for a clean URL ("/faq") matches the file faq.html; one with a trailing slash or splat matches a folder
    const hit = files.some((p) => {
      const url = "/" + p;
      const folder = url.replace(/\/index\.html$/, "");
      return re.test(url) || re.test(url.replace(/\.html$/, "")) || re.test(folder) || re.test(folder + "/");
    });
    if (!hit) err(`${neg}: matches no file under apps/web/public (stale pattern)`);
    if (/^\/(webapp|recovery|api|build|me|app|join|studio)(\/|$)/.test(neg)) err(`${neg}: that folder is the Worker's (redirects, rewrites or an API)`);
  }

  // recovery. is served by this Worker from /recovery/, and a file it shares with the site root
  // (favicons) is fetched from the root once the Worker no longer sees it: the bytes must match.
  for (const rel of listFiles(join(publicDir, "recovery"))) {
    const root = join(publicDir, rel);
    if (existsSync(root) && !reachesWorker(patterns, "/" + rel) &&
        !readFileSync(root).equals(readFileSync(join(publicDir, "recovery", rel)))) {
      err(`/${rel} is served directly but recovery/${rel} differs: recovery. would get the wrong file`);
    }
  }

  const sitePublic = /^SITE_PUBLIC\s*=\s*"(1|true)"/m.test(toml);
  if (directPatterns(patterns).length > 0 && !sitePublic) {
    err('SITE_PUBLIC is not "1": the coming-soon gate would be armed, and files served without the Worker skip it. Re-arming the gate means run_worker_first = ["/*"].');
  }

  const headersPath = join(root, SITE_HEADERS_PATH);
  const want = siteHeadersFile(patterns);
  if (!existsSync(headersPath)) err(`${SITE_HEADERS_PATH} is missing: run npx tsx scripts/static-assets.ts write-headers`);
  else if (readFileSync(headersPath, "utf8") !== want) err(`${SITE_HEADERS_PATH} is out of date with run_worker_first: run npx tsx scripts/static-assets.ts write-headers`);
  if (countHeaderRules(want) > MAX_HEADER_RULES) err(`_headers would have ${countHeaderRules(want)} rules; Cloudflare allows ${MAX_HEADER_RULES}`);

  // The shell hosts are served by the static-only Worker, not this one.
  if (/^\s*\{\s*pattern\s*=\s*"(webapp|remote)\.flagshipserver\.com"/m.test(toml)) {
    err("webapp. / remote. are routes of flagship-webapp (apps/webapp-static), not of flagship-com");
  }
  return f;
}

// ---- CLI -------------------------------------------------------------------

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [cmd, arg] = process.argv.slice(2);
  if (cmd === "check") {
    const findings = checkStaticAssets();
    for (const x of findings) console.error(`static-assets: ${x.message}`);
    if (findings.length) process.exit(1);
    console.log("static-assets: ok");
  } else if (cmd === "write-headers") {
    const patterns = readWorkerFirst(readFileSync(join(REPO_ROOT, "apps/com/wrangler.toml"), "utf8"));
    writeFileSync(join(REPO_ROOT, SITE_HEADERS_PATH), siteHeadersFile(patterns));
    console.log(`wrote ${SITE_HEADERS_PATH} (${countHeaderRules(siteHeadersFile(patterns))} rules)`);
  } else if (cmd === "build-webapp") {
    const out = arg ?? join(REPO_ROOT, "apps/webapp-static/public");
    const r = await buildWebappAssets(out);
    console.log(`built ${out}: ${r.files} files`);
  } else {
    console.error("usage: static-assets.ts check | write-headers | build-webapp [outDir]");
    process.exit(2);
  }
}
