#!/usr/bin/env node
// Builds apps/web/public/webapp/vendor/flagship-org/org.js: the org protocol (packages/protocol
// orgAuthority, orgKeyRing, orgDirectory, orgConnector and the hybrid primitives they sign with) bundled for the
// browser, so the webapp acts as an org seat with exactly the code `.com`, the box and the protocol
// tests run (docs/webapp-key-custody.md item 1). The shell installs it like any other file (its
// SHA-256 is in the signed shell manifest); seeds are passed in per call and never stored by it.
//
//   node scripts/build-webapp-org-vendor.mjs          rebuild
//   node scripts/build-webapp-org-vendor.mjs --check  fail if the committed file is stale
import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "apps/web/public/webapp/vendor/flagship-org/org.js");
const SRC = "./packages/protocol/src";
const entry = [
  `export * from "${SRC}/orgAuthority.ts";`,
  `export * from "${SRC}/orgKeyRing.ts";`,
  `export * from "${SRC}/orgDirectory.ts";`,
  `export * from "${SRC}/orgConnector.ts";`,
  `export { hybridSigKeygen, hybridSign, hybridSealKeygen } from "${SRC}/pqHybrid.ts";`,
  `export { signPqKeyBinding, pqKeyBindingFromWire, verifyPqKeyBinding, messagePurpose } from "${SRC}/pqTrust.ts";`,
  "",
].join("\n");

const r = await build({
  stdin: { contents: entry, resolveDir: ROOT, sourcefile: "org-entry.js" },
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  write: false,
  legalComments: "none",
  minify: false,
  treeShaking: true,
});
const header =
  "// Generated by scripts/build-webapp-org-vendor.mjs from packages/protocol (orgAuthority, orgKeyRing, orgDirectory, orgConnector,\n" +
  "// pqHybrid, pqTrust) and the @noble libraries they use (MIT, Paul Miller). Do not edit.\n";
const text = header + r.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
    console.error(`${OUT} is stale: node scripts/build-webapp-org-vendor.mjs`);
    process.exit(1);
  }
  console.log("org.js is fresh");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${text.length} bytes)`);
}
