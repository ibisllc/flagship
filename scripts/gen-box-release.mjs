#!/usr/bin/env node
// The box release the apps and builders compile in (SEC-INSTALL-001).
//
// Sources of truth, all under release/:
//   box-release.json         the exact commit + manifest sequence new servers install, where artifacts are served,
//                            the stack new boxes are built on and whether the app browser is on
//   box-artifact-trust.json  who may sign an artifact manifest, and how many must
//   security-floor.json      the lowest Node a box may run
//
//   node scripts/gen-box-release.mjs --write    rewrite the generated constants
//   node scripts/gen-box-release.mjs --check    exit 1 if any generated file differs (the default)
//
// Generated: packages/protocol/src/boxReleaseConfig.ts (the TS builder, bundled
// into the Mac/Android engines), the webapp's lib/boxRelease.js, iOS
// BoxRelease.swift and Android BoxRelease.kt. The apps use `commit` as the
// default installerGitRef; the installer script uses all of it.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(process.env.FLAGSHIP_ROOT ?? join(HERE, ".."));

export function load(root = ROOT) {
  const rel = JSON.parse(readFileSync(join(root, "release/box-release.json"), "utf8"));
  const trust = JSON.parse(readFileSync(join(root, "release/box-artifact-trust.json"), "utf8"));
  const floor = JSON.parse(readFileSync(join(root, "release/security-floor.json"), "utf8"));
  const errors = [];
  if (!/^[0-9a-f]{40}$/.test(rel.commit ?? "")) errors.push(`box-release.json commit must be 40 lowercase hex (got ${JSON.stringify(rel.commit)})`);
  if (!Number.isInteger(rel.sequence) || rel.sequence < 0) errors.push("box-release.json sequence must be a non-negative integer");
  if (!/^https:\/\/[A-Za-z0-9.-]+(\/[A-Za-z0-9._/-]*)?$/.test(rel.artifactBase ?? "") || String(rel.artifactBase).endsWith("/")) errors.push("box-release.json artifactBase must be an https URL without a trailing slash");
  if (!Number.isInteger(trust.threshold) || trust.threshold < 1) errors.push("trust threshold must be >= 1");
  if (!Array.isArray(trust.keys) || trust.keys.length < trust.threshold || trust.keys.some((k) => !/^[0-9a-f]{64}$/.test(k))) errors.push("trust keys must be 64-hex and at least threshold many");
  if (new Set(trust.keys).size !== trust.keys.length) errors.push("trust keys must be distinct");
  if (!/^\d+\.\d+\.\d+$/.test(floor.node?.minimum ?? "")) errors.push("security-floor node.minimum must be x.y.z");
  const newBoxStack = rel.newBoxStack ?? "arch-v2";
  if (newBoxStack !== "arch-v2" && newBoxStack !== "classic") errors.push(`box-release.json newBoxStack must be "arch-v2" or "classic" (got ${JSON.stringify(rel.newBoxStack)})`);
  // Absent means off: a release turns the app browser on only by saying so.
  const appBrowser = rel.appBrowser ?? false;
  if (typeof appBrowser !== "boolean") errors.push(`box-release.json appBrowser must be true or false (got ${JSON.stringify(rel.appBrowser)})`);
  const pq = trust.pq ?? { keyIds: [], legacyManifests: [] };
  const hex32 = (l) => Array.isArray(l) && l.every((k) => /^[0-9a-f]{64}$/.test(k));
  if (!hex32(pq.keyIds) || !hex32(pq.legacyManifests)) errors.push("trust pq keyIds and legacyManifests must be 64-hex lists");
  return { value: { commit: rel.commit, sequence: rel.sequence, artifactBase: rel.artifactBase, trustKeys: trust.keys, trustThreshold: trust.threshold, nodeFloor: floor.node?.minimum, pq, newBoxStack, appBrowser }, errors };
}

const BANNER = "GENERATED by scripts/gen-box-release.mjs from release/*.json: do not edit. Run `node scripts/gen-box-release.mjs --write`.";

export function files(v, root = ROOT) {
  // The installer scripts run on a box before anything of the artifact exists, so the generated
  // bootstrap carries their text itself. They are strings, not code, in the builder bundle.
  const verifySh = readFileSync(join(root, "installer/verify-box-artifact.sh"), "utf8");
  const installSh = readFileSync(join(root, "installer/install-box-artifact.sh"), "utf8");
  const keysTs = v.trustKeys.map((k) => `  "${k}",`).join("\n");
  const pq = v.pq ?? { keyIds: [], legacyManifests: [] };
  const list = (l) => (l.length ? `[${l.map((k) => `"${k}"`).join(", ")}]` : "[]");
  // What the installer adds for the PQ pin: nothing until the pin names a key.
  const pqArgs = pq.keyIds.length
    ? ` --pq-key-ids "${pq.keyIds.join(",")}"` + (pq.legacyManifests.length ? ` --legacy-manifests "${pq.legacyManifests.join(",")}"` : "")
    : "";
  const scriptsModule = `// ${BANNER}
// installer/verify-box-artifact.sh and installer/install-box-artifact.sh, verbatim.
export const VERIFY_BOX_ARTIFACT_SH: string = ${JSON.stringify(verifySh)};
export const INSTALL_BOX_ARTIFACT_SH: string = ${JSON.stringify(installSh)};
`;
  const releaseModule = `// ${BANNER}
export const BOX_RELEASE = {
  /** The exact source commit new servers install. Never a branch or a tag. */
  commit: "${v.commit}",
  /** The manifest sequence a box must not go below. */
  minSequence: ${v.sequence},
  artifactBase: "${v.artifactBase}",
  trust: {
    threshold: ${v.trustThreshold},
    keys: [
${keysTs}
    ],
    /** The hybrid PQ pin (boxArtifactPq.ts): signers' key ids, and manifests from before the cut-over. */
    pq: { keyIds: ${list(pq.keyIds)} as readonly string[], legacyManifests: ${list(pq.legacyManifests)} as readonly string[] },
  },
  /** The installer's arguments for the PQ pin; empty while the pin names no key. */
  pqInstallerArgs: ${JSON.stringify(pqArgs)},
  /** The lowest Node a box may run. */
  nodeFloor: "${v.nodeFloor}",
  /** What a new box is built on: Podman + the Rust path, or Docker + TS (the release gym decides). */
  newBoxStack: "${v.newBoxStack ?? "arch-v2"}" as "arch-v2" | "classic",
  /** Whether a box turns the policed app browser on (SEC-BROWSER-002): on only when the release gym proved it. */
  appBrowser: ${v.appBrowser === true} as boolean,
} as const;
`;
  return {
    "packages/protocol/src/boxReleaseConfig.ts": releaseModule,
    "packages/flagship-builder/src/boxReleaseConfig.ts": releaseModule,
    "packages/control-plane/src/boxReleaseConfig.ts": releaseModule,
    "packages/flagship-builder/src/boxInstallerScripts.ts": scriptsModule,
    "packages/control-plane/src/boxInstallerScripts.ts": scriptsModule,
    // The container stacks (packages/flagship-builder/src/engineSetup.ts, the one source), so the demo and
    // gym cloud-init builds a box exactly as the installer and the appliance do.
    "packages/control-plane/src/boxStack.ts": `// ${BANNER}\n// packages/flagship-builder/src/engineSetup.ts, verbatim.\n${readFileSync(join(root, "packages/flagship-builder/src/engineSetup.ts"), "utf8")}`,
    "apps/web/public/webapp/lib/boxRelease.js": `// ${BANNER}
// The box release new servers install: the default installerGitRef is this exact commit.
export const BOX_RELEASE_COMMIT = "${v.commit}";
export const BOX_RELEASE_SEQUENCE = ${v.sequence};
`,
    "apps/mobile/shared/Sources/FlagshipCore/BoxRelease.swift": `// ${BANNER}

/// The box release new servers install: the default \`installerGitRef\` is this exact commit.
public enum BoxRelease {
    public static let commit = "${v.commit}"
    public static let sequence = ${v.sequence}
}
`,
    "apps/mobile/android/app/src/main/java/com/flagshipserver/app/core/BoxRelease.kt": `// ${BANNER}

package com.flagshipserver.app.core

/** The box release new servers install: the default \`installerGitRef\` is this exact commit. */
object BoxRelease {
    const val COMMIT = "${v.commit}"
    const val SEQUENCE = ${v.sequence}
}
`,
  };
}

function main() {
  const write = process.argv.includes("--write");
  const { value, errors } = load();
  if (errors.length) {
    console.error(errors.map((e) => `✗ ${e}`).join("\n"));
    process.exit(1);
  }
  let drift = 0;
  for (const [rel, want] of Object.entries(files(value, ROOT))) {
    const abs = join(ROOT, rel);
    const have = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (have === want) continue;
    if (write) {
      writeFileSync(abs, want);
      console.log(`wrote ${rel}`);
    } else {
      drift++;
      console.error(`✗ ${rel} differs from release/*.json (run: node scripts/gen-box-release.mjs --write)`);
    }
  }
  if (drift) process.exit(1);
  if (!write) console.log("box release constants are in sync");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
